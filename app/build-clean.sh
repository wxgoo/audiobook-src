#!/usr/bin/env bash
# =============================================================================
# 构建垃圾清理脚本（仅限 NAS / 本机执行，不要在沙箱内直接运行）
# -----------------------------------------------------------------------------
# build.sh 会把旧的 .nuxt / dist 改名归档到 ../.build-trash（rename，不删除），
# 本脚本负责在「允许批量删除」的环境里把它们彻底清掉，释放磁盘。
#
# 用法：
#   cd app && ./build-clean.sh
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")"

TRASH="../.build-trash"
if [ -d "$TRASH" ]; then
  rm -rf "$TRASH"
  echo "已清理构建垃圾：$TRASH"
else
  echo "没有可清理的构建垃圾（$TRASH 不存在）"
fi
